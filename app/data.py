def build_questions():
    questions = []

    for index, question_text in enumerate(QUESTION_STEMS):
        source_options = OPTION_SETS[
            index % len(OPTION_SETS)
        ]

        shift = (
            index // len(OPTION_SETS)
        ) * 2

        shift %= len(source_options)

        rotated_options = (
            source_options[shift:]
            + source_options[:shift]
        )

        questions.append(
            {
                "text": question_text,
                "options": rotated_options,
            }
        )

    return questions


