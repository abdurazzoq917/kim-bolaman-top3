def build_careers():
    careers = {}
    career_number = 1

    for domain_key, titles in CAREER_TITLES.items():
        domain = DOMAINS[domain_key]

        for title in titles:
            title_lower = title.lower()
            traits = list(domain["traits"])

            for keywords, extra_traits in KEYWORD_TRAITS:
                if any(
                    keyword in title_lower
                    for keyword in keywords
                ):
                    traits.extend(extra_traits)

            traits = list(dict.fromkeys(traits))

            careers[f"career_{career_number}"] = {
                "title": title,
                "domain": domain_key,
                "domain_name": domain["name"],
                "emoji": domain["emoji"],
                "description": (
                    f"{title} — "
                    f"{domain['name'].lower()} "
                    "yo‘nalishidagi kasb. "
                    f"Bu kasbda "
                    f"{', '.join(domain['skills'][:3]).lower()} "
                    "kabi ko‘nikmalar muhim."
                ),
                "skills": domain["skills"],
                "tools": domain["tools"],
                "roadmap": domain["roadmap"],
                "first_project": (
                    f"{title} kasbini sinab ko‘rish "
                    "uchun kichik amaliy loyiha "
                    "yoki bir kunlik kuzatuv "
                    "topshirig‘ini bajaring."
                ),
                "traits": traits,
            }

            career_number += 1

    return careers


CAREERS = build_careers()


